"""Helpers shared by every `formcoach eval`/`data profile` report writer.

Reports are Markdown files under ``reports/`` (plus PNGs under ``reports/figures/``) that are
regenerated by commands, never edited by hand. Every report starts with :func:`header`, which
records the date, the command, the git commit, the seed and the package version so a number
in the written report can be traced back to the run that produced it.
"""

from __future__ import annotations

import subprocess
from datetime import datetime
from pathlib import Path

import pandas as pd

from formcoach import __version__

SEED = 20260924
REPO_ROOT = Path(__file__).resolve().parents[3]
REPORTS_DIR = REPO_ROOT / "reports"
FIGURES_DIR = REPORTS_DIR / "figures"


def git_commit() -> str:
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=REPO_ROOT,
            capture_output=True,
            text=True,
            timeout=10,
            check=False,
        )
        return out.stdout.strip() or "unknown"
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def header(title: str, command: str, seed: int | None = SEED, extra: dict | None = None) -> str:
    """Markdown title + provenance block for a generated report."""
    lines = [
        f"# {title}",
        "",
        f"Generated by `{command}` on {datetime.now().strftime('%Y-%m-%d %H:%M')} · "
        f"formcoach {__version__} · commit `{git_commit()}`"
        + (f" · seed {seed}" if seed is not None else ""),
        "",
        "_Do not edit: regenerate with the command above (CLAUDE.md rule 3)._",
        "",
    ]
    for k, v in (extra or {}).items():
        lines.append(f"- **{k}:** {v}")
    if extra:
        lines.append("")
    return "\n".join(lines)


def md_table(df: pd.DataFrame, floatfmt: str = ".3f", index: bool = False) -> str:
    """Render a DataFrame as a GitHub Markdown table (no tabulate dependency)."""
    if index:
        df = df.reset_index()
    cols = [str(c) for c in df.columns]

    def fmt(v) -> str:
        if isinstance(v, float):
            return format(v, floatfmt) if v == v else ""
        return str(v).replace("|", "\\|")

    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for row in df.itertuples(index=False):
        lines.append("| " + " | ".join(fmt(v) for v in row) + " |")
    return "\n".join(lines)


def relative_figure(path: Path, report_path: Path) -> str:
    """Markdown image link from ``report_path``'s directory to ``path``."""
    try:
        rel = path.relative_to(report_path.parent)
    except ValueError:
        rel = path
    return f"![{path.stem}]({rel.as_posix()})"
